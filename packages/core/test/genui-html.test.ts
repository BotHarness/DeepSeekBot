import { describe, expect, it } from 'vitest';
import {
  buildGenuiHtmlDocument,
  GENUI_HTML_POLICY_VERSION,
  parseGenuiHtmlMessage,
} from '../src/channels/genui-html.js';

const document = {
  version: 2 as const,
  snapshotId: 'synthetic-html-1',
  observedAt: '2026-11-08T00:00:00.000Z',
  title: 'Synthetic HTML',
  html: '<h2>Safe <em>composition</em></h2><script>document.body.dataset.local = "yes"</script>',
};

describe('isolated HTML compiler', () => {
  it('builds the same bytes for preview and final presentation with the same inputs', () => {
    const options = { instanceId: 'test-frame', theme: 'dark' as const };
    const result = buildGenuiHtmlDocument(document, options);
    expect(buildGenuiHtmlDocument(document, options)).toEqual(result);
    expect(result.policyVersion).toBe(GENUI_HTML_POLICY_VERSION);
    expect(result.html).toContain('sandbox="allow-scripts"');
    expect(result.html).toContain("frame-src 'none'");
    expect(result.html).not.toContain('allow-same-origin');
    expect(result.html).toContain('\\u003cscript>');
  });

  it('keeps the immutable document identity independent of runtime instance and theme', () => {
    const first = buildGenuiHtmlDocument(document, { instanceId: 'one', theme: 'dark' });
    const second = buildGenuiHtmlDocument(document, { instanceId: 'two', theme: 'light' });
    expect(first.documentId).toBe(second.documentId);
    expect(first.html).not.toBe(second.html);
    const changed = buildGenuiHtmlDocument(
      { ...document, html: `${document.html}<p>New</p>` },
      { instanceId: 'one', theme: 'dark' },
    );
    expect(changed.documentId).not.toBe(first.documentId);
  });

  it('rejects frame identity injection and invalid restored state', () => {
    expect(() =>
      buildGenuiHtmlDocument(document, { instanceId: '"><script>', theme: 'dark' }),
    ).toThrow();
    expect(() =>
      buildGenuiHtmlDocument(document, {
        instanceId: 'test',
        theme: 'dark',
        state: { version: 1, values: { unknown: true } },
      }),
    ).toThrow();
  });

  it('does not let markup in generated bytes terminate the trusted guardian script', () => {
    const result = buildGenuiHtmlDocument(
      { ...document, html: '</script><script nonce="genui-guardian">throw 1</script>' },
      { instanceId: 'test', theme: 'light' },
    );
    expect(result.html.match(/<script /gu)).toHaveLength(1);
    expect(result.html.match(/<\/script>/gu)).toHaveLength(1);
  });
});

describe('checked HTML presentation messages', () => {
  const message = {
    protocol: 'botharness-genui-v1',
    instanceId: 'test',
    sequence: 1,
    type: 'ready',
  };

  it('accepts only the current instance protocol and known message types', () => {
    expect(parseGenuiHtmlMessage(message, 'test')).toEqual(message);
    expect(parseGenuiHtmlMessage(message, 'other')).toBeUndefined();
    expect(parseGenuiHtmlMessage({ ...message, type: 'callTool' }, 'test')).toBeUndefined();
    expect(parseGenuiHtmlMessage({ ...message, protocol: 'other' }, 'test')).toBeUndefined();
    for (const sequence of [undefined, 0, -1, 1.5, Infinity])
      expect(parseGenuiHtmlMessage({ ...message, sequence }, 'test')).toBeUndefined();
  });

  it('rejects invalid height, oversized messages and nonprimitive state', () => {
    for (const height of [-1, Infinity, NaN, 20_001])
      expect(parseGenuiHtmlMessage({ ...message, type: 'height', height }, 'test')).toBeUndefined();
    expect(
      parseGenuiHtmlMessage({ ...message, type: 'error', message: 'x'.repeat(20_000) }, 'test'),
    ).toBeUndefined();
    expect(
      parseGenuiHtmlMessage(
        { ...message, type: 'state', state: { version: 1, values: { bad: [] } } },
        'test',
      ),
    ).toBeUndefined();
    expect(
      parseGenuiHtmlMessage(
        { ...message, type: 'state', state: { version: 1, values: { constructor: 'bad' } } },
        'test',
      ),
    ).toBeUndefined();
  });
});
