import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { MOBILE_EVENT_FIELDS } from '../../../apps/mobile/src/telemetry/schema.js';
import { LEGACY_EVENT_NAMES } from '../../ingest/src/taxonomy.js';
import {
  RESERVED_TELEMETRY_EVENTS,
  TELEMETRY_CATEGORIES,
  TELEMETRY_EVENTS,
  TELEMETRY_SURFACES,
  TELEMETRY_VERBS,
  telemetryNameIsWellFormed,
  type TelemetryPropertySpec,
} from '../src/telemetry/events.js';

const PLAN = new URL('../../../docs/telemetry-events.md', import.meta.url);

const unpadded = (markdown: string) =>
  markdown
    .split('\n')
    .map((line) =>
      line.startsWith('|') ? line.replace(/ {2,}/gu, ' ').replace(/-{3,}/gu, '---') : line,
    )
    .join('\n');

const code = (value: string) => `\`${value}\``;
const spec = (value: TelemetryPropertySpec) =>
  value === 'boolean' ? 'boolean' : value === 'count' ? 'count' : value.join(' \\| ');

function renderPlan(): string {
  const host = Object.entries(TELEMETRY_EVENTS)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, event]) => {
      const properties = Object.entries(event.properties)
        .map(([key, value]) => `${code(key)}: ${spec(value)}`)
        .join('<br>');
      return `| ${code(name)} | ${event.origin === 'host' ? 'Host' : 'Web Client'} | ${event.description} | ${properties || '—'} |`;
    });
  const mobile = Object.entries(MOBILE_EVENT_FIELDS)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, fields]) => `| ${code(name)} | ${Object.keys(fields).map(code).join(', ')} |`);
  const legacy = Object.entries(LEGACY_EVENT_NAMES)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([from, to]) => `| ${code(from)} | ${code(to)} |`);
  return `<!-- Generated by \`pnpm telemetry:plan\` from packages/core/src/telemetry/events.ts, apps/mobile/src/telemetry/schema.ts and packages/ingest/src/taxonomy.ts. Do not edit. -->

# Telemetry tracking plan

Every analytics event the Host, the Web Client and the mobile app send, under the naming rules of [ADR-0270](adr/0270-telemetry-events-follow-one-tracking-plan.md). The product site keeps its own list in the deepseekbot-site repository under the same rules.

## Naming

- Event: \`category:object_action\`, lowercase snake_case, a present-tense verb. The same behavior has the same name on every source; \`source\` tells them apart.
- Categories: ${TELEMETRY_CATEGORIES.map(code).join(' ')}
- Verbs: ${TELEMETRY_VERBS.map(code).join(' ')}
- Outcomes are one \`_complete\` event with an \`outcome\` property, never separate success and failure events.
- Properties: \`object_adjective\`; booleans start with \`is_\` or \`has_\`, counts end with \`_count\`, bands with \`_bucket\`, times with \`_timestamp\`.

## Properties on every event

| Property | Values |
| --- | --- |
| \`source\` | \`host\` \\| \`mobile\` \\| \`site\` \\| \`links\` |
| \`app_version\` | Host package or mobile app version |
| \`surface\` | ${TELEMETRY_SURFACES.map(code).join(' \\| ')} (Host feature events) |

## Host and Web Client

| Event | Sent by | Meaning | Properties |
| --- | --- | --- | --- |
${host.join('\n')}

Also sent unchanged: ${RESERVED_TELEMETRY_EVENTS.map(code).join(', ')}.

## Mobile app

Each event also carries the common mobile context described in [mobile statistics](mobile-statistics.md).

| Event | Properties |
| --- | --- |
${mobile.join('\n')}

## Renamed at ingest

Clients released before this plan still send the old names; the \`t.botharness.ai\` proxy renames them, and the old \`plugin\` source and \`plugin_version\`, before PostHog stores them.

| Old name | Current name |
| --- | --- |
${legacy.join('\n')}
`;
}

describe('telemetry tracking plan', () => {
  it('names every registered event by the convention', () => {
    for (const name of [...Object.keys(TELEMETRY_EVENTS), ...Object.keys(MOBILE_EVENT_FIELDS)])
      expect(telemetryNameIsWellFormed(name), name).toBe(true);
  });

  it('keeps docs/telemetry-events.md generated from the registries', () => {
    const plan = renderPlan();
    if (process.env['BOTHARNESS_WRITE_TELEMETRY_PLAN'] === '1') {
      writeFileSync(PLAN, plan);
      execFileSync('pnpm', ['exec', 'oxfmt', '--write', fileURLToPath(PLAN)]);
    }
    expect(unpadded(readFileSync(PLAN, 'utf8')), 'run pnpm telemetry:plan').toBe(unpadded(plan));
  });
});
