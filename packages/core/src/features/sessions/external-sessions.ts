import { open, readdir, readFile, stat } from 'node:fs/promises';
import { homedir } from 'node:os';
import { basename, join } from 'node:path';

export const EXTERNAL_SESSION_SOURCES = ['claude-code', 'codex'] as const;
export type ExternalSessionSource = (typeof EXTERNAL_SESSION_SOURCES)[number];

export const EXTERNAL_SESSION_LIST_MAX = 500;
const HEAD_BYTES = 256 * 1024;
const READ_BYTES = 16 * 1024 * 1024;
const MESSAGE_CHARS = 4000;
const MARKDOWN_CHARS = 120_000;
const TITLE_CHARS = 120;
const TOOL_CHARS = 160;
const ID = /^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$/u;

export interface ExternalSessionSummary {
  sessionId: string;
  source: ExternalSessionSource;
  title?: string;
  cwd: string;
  lastActivityAt: number;
}

export interface ExternalSessionEntry {
  role: 'human' | 'assistant' | 'tool';
  text: string;
  at?: string;
}

export interface ExternalSessionSnapshot extends ExternalSessionSummary {
  entries: ExternalSessionEntry[];
}

export interface ExternalSessionReader {
  list(): Promise<ExternalSessionSummary[]>;
  read(sessionId: string): Promise<ExternalSessionSnapshot | undefined>;
}

export function isExternalSessionId(id: string): boolean {
  return parseExternalSessionId(id) !== undefined;
}

export function parseExternalSessionId(
  id: string,
): { source: ExternalSessionSource; id: string } | undefined {
  const at = id.indexOf(':');
  if (at < 0) return undefined;
  const source = id.slice(0, at);
  const rest = id.slice(at + 1);
  if (!(EXTERNAL_SESSION_SOURCES as readonly string[]).includes(source) || !ID.test(rest))
    return undefined;
  return { source: source as ExternalSessionSource, id: rest };
}

export function externalSessionLabel(source: ExternalSessionSource): string {
  return source === 'claude-code' ? 'Claude Code' : 'Codex';
}

function record(line: string): Record<string, unknown> | undefined {
  if (line.trim() === '') return undefined;
  try {
    const value: unknown = JSON.parse(line);
    return value !== null && typeof value === 'object' && !Array.isArray(value)
      ? (value as Record<string, unknown>)
      : undefined;
  } catch {
    return undefined;
  }
}

function str(value: unknown): string | undefined {
  return typeof value === 'string' && value.trim() !== '' ? value : undefined;
}

function oneLine(text: string, max: number): string {
  const flat = text.replace(/\s+/gu, ' ').trim();
  return flat.length > max ? flat.slice(0, max - 1) + '…' : flat;
}

function clip(text: string): string {
  const trimmed = text.trim();
  return trimmed.length > MESSAGE_CHARS ? trimmed.slice(0, MESSAGE_CHARS - 1) + '…' : trimmed;
}

const INJECTED = [
  '<environment_context',
  '<user_instructions',
  '<command-name>',
  '<command-message>',
  '<local-command-',
  '<system-reminder>',
  'Caveat: The messages below were generated by the user while running local commands',
  '# AGENTS.md instructions',
];

function injected(text: string): boolean {
  const start = text.trimStart();
  return INJECTED.some((prefix) => start.startsWith(prefix));
}

function blocks(
  content: unknown,
): { type: string; text?: string; name?: string; input?: unknown }[] {
  if (typeof content === 'string') return [{ type: 'text', text: content }];
  if (!Array.isArray(content)) return [];
  return content.flatMap((block) =>
    block !== null && typeof block === 'object'
      ? [block as { type: string; text?: string; name?: string; input?: unknown }]
      : [],
  );
}

function toolLine(name: string, input: unknown): string {
  let target: string | undefined;
  if (input !== null && typeof input === 'object') {
    const args = input as Record<string, unknown>;
    target =
      str(args['command']) ??
      str(args['file_path']) ??
      str(args['path']) ??
      str(args['url']) ??
      str(args['pattern']) ??
      str(args['description']);
  } else if (typeof input === 'string') {
    try {
      return toolLine(name, JSON.parse(input));
    } catch {
      target = input;
    }
  }
  return target === undefined
    ? name
    : `${name} \`${oneLine(target, TOOL_CHARS).replaceAll('`', "'")}\``;
}

export function parseClaudeCodeSession(text: string): Omit<
  ExternalSessionSnapshot,
  'sessionId' | 'source' | 'lastActivityAt'
> & {
  id?: string;
} {
  let cwd: string | undefined;
  let id: string | undefined;
  let summary: string | undefined;
  let first: string | undefined;
  const entries: ExternalSessionEntry[] = [];
  for (const line of text.split('\n')) {
    const row = record(line);
    if (row === undefined) continue;
    const type = row['type'];
    if (type === 'summary') summary ??= str(row['summary']);
    const named = str(row['customTitle']) ?? str(row['aiTitle']);
    if (named !== undefined) summary = named;
    if (type !== 'user' && type !== 'assistant') continue;
    if (row['isSidechain'] === true || row['isMeta'] === true || row['isCompactSummary'] === true)
      continue;
    cwd ??= str(row['cwd']);
    id ??= str(row['sessionId']);
    const at = str(row['timestamp']);
    const message = row['message'] as { content?: unknown; model?: unknown } | undefined;
    if (message?.model === '<synthetic>') continue;
    for (const block of blocks(message?.content)) {
      if (block.type === 'text' && typeof block.text === 'string') {
        if (block.text.trim() === '' || injected(block.text)) continue;
        const role = type === 'user' ? 'human' : 'assistant';
        if (role === 'human') first ??= block.text;
        entries.push({ role, text: clip(block.text), ...(at === undefined ? {} : { at }) });
      } else if (block.type === 'tool_use' && typeof block.name === 'string') {
        entries.push({
          role: 'tool',
          text: toolLine(block.name, block.input),
          ...(at === undefined ? {} : { at }),
        });
      }
    }
  }
  const title = summary ?? first;
  return {
    ...(id === undefined ? {} : { id }),
    cwd: cwd ?? '',
    ...(title === undefined ? {} : { title: oneLine(title, TITLE_CHARS) }),
    entries,
  };
}

function codexText(content: unknown): string {
  return blocks(content)
    .flatMap((block) =>
      (block.type === 'input_text' || block.type === 'output_text' || block.type === 'text') &&
      typeof block.text === 'string'
        ? [block.text]
        : [],
    )
    .join('\n');
}

export function parseCodexSession(text: string): Omit<
  ExternalSessionSnapshot,
  'sessionId' | 'source' | 'lastActivityAt'
> & {
  id?: string;
} {
  let cwd: string | undefined;
  let id: string | undefined;
  let first: string | undefined;
  let subagent = false;
  const entries: ExternalSessionEntry[] = [];
  for (const line of text.split('\n')) {
    const row = record(line);
    if (row === undefined) continue;
    const at = str(row['timestamp']);
    if (row['type'] === 'session_meta') {
      const meta = (row['payload'] ?? {}) as Record<string, unknown>;
      id ??= str(meta['id']) ?? str(meta['session_id']);
      cwd ??= str(meta['cwd']);
      const origin = meta['source'];
      if (origin !== null && typeof origin === 'object' && 'subagent' in origin) subagent = true;
      continue;
    }
    if (row['type'] === 'turn_context') {
      cwd ??= str((row['payload'] as Record<string, unknown> | undefined)?.['cwd']);
      continue;
    }
    const item = (row['type'] === 'response_item' ? row['payload'] : row) as
      | Record<string, unknown>
      | undefined;
    if (item === undefined || item === null) continue;
    if (row['type'] === undefined && id === undefined && str(row['id']) && 'instructions' in row) {
      id = str(row['id']);
      continue;
    }
    if (item['type'] === 'message') {
      const role =
        item['role'] === 'user' ? 'human' : item['role'] === 'assistant' ? 'assistant' : undefined;
      if (role === undefined) continue;
      const body = codexText(item['content']);
      if (body.trim() === '' || injected(body)) continue;
      if (role === 'human') first ??= body;
      entries.push({ role, text: clip(body), ...(at === undefined ? {} : { at }) });
    } else if (item['type'] === 'function_call' || item['type'] === 'custom_tool_call') {
      const name = str(item['name']) ?? 'tool';
      entries.push({
        role: 'tool',
        text: toolLine(name, item['arguments'] ?? item['input']),
        ...(at === undefined ? {} : { at }),
      });
    } else if (item['type'] === 'local_shell_call') {
      const action = item['action'] as { command?: unknown } | undefined;
      const command = Array.isArray(action?.command) ? action.command.join(' ') : undefined;
      entries.push({
        role: 'tool',
        text: toolLine('shell', command === undefined ? undefined : { command }),
        ...(at === undefined ? {} : { at }),
      });
    }
  }
  return {
    ...(id === undefined ? {} : { id }),
    cwd: subagent ? '' : (cwd ?? ''),
    ...(first === undefined ? {} : { title: oneLine(first, TITLE_CHARS) }),
    entries,
  };
}

export function renderExternalSessionMarkdown(session: ExternalSessionSnapshot): string {
  const header = [
    `# ${oneLine(session.title ?? 'Untitled session', TITLE_CHARS)}`,
    '',
    `${externalSessionLabel(session.source)} session \`${session.sessionId}\` in \`${session.cwd}\`. Imported read-only from the Host's local ${externalSessionLabel(session.source)} history.`,
  ];
  const sections: string[] = [];
  let tools: string[] = [];
  const flush = () => {
    if (tools.length === 0) return;
    sections.push(['Tools:', ...tools.map((tool) => `- ${tool}`)].join('\n'));
    tools = [];
  };
  for (const entry of session.entries) {
    if (entry.role === 'tool') {
      tools.push(entry.text);
      continue;
    }
    flush();
    const who = entry.role === 'human' ? 'Human' : 'Assistant';
    sections.push(`## ${who}${entry.at === undefined ? '' : ` · ${entry.at}`}\n\n${entry.text}`);
  }
  flush();
  let size = header.join('\n').length;
  let kept = sections.length;
  for (let index = sections.length - 1; index >= 0; index -= 1) {
    size += sections[index]!.length + 2;
    if (size > MARKDOWN_CHARS) break;
    kept = index;
  }
  const omitted = kept;
  const body = sections.slice(kept);
  if (omitted > 0) header.push('', `_${omitted} earlier entries are not shown._`);
  return [...header, ...body.flatMap((section) => ['', section])].join('\n') + '\n';
}

interface SessionFile {
  source: ExternalSessionSource;
  path: string;
  mtimeMs: number;
  size: number;
}

async function files(
  dir: string,
  depth: number,
  match: (name: string) => boolean,
): Promise<string[]> {
  let names;
  try {
    names = await readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const found: string[] = [];
  for (const entry of names) {
    const path = join(dir, entry.name);
    if (entry.isDirectory() && depth > 0) found.push(...(await files(path, depth - 1, match)));
    else if (entry.isFile() && match(entry.name)) found.push(path);
  }
  return found;
}

async function head(path: string, bytes: number): Promise<string> {
  const handle = await open(path, 'r');
  try {
    const buffer = Buffer.alloc(bytes);
    const { bytesRead } = await handle.read(buffer, 0, bytes, 0);
    const text = buffer.subarray(0, bytesRead).toString('utf8');
    if (bytesRead < bytes) return text;
    const end = text.lastIndexOf('\n');
    return end < 0 ? '' : text.slice(0, end);
  } finally {
    await handle.close();
  }
}

async function tail(path: string, start: number, size: number): Promise<string> {
  const handle = await open(path, 'r');
  try {
    const buffer = Buffer.alloc(size - start + 1);
    const { bytesRead } = await handle.read(buffer, 0, buffer.length, start - 1);
    const text = buffer.subarray(0, bytesRead).toString('utf8');
    return text.slice(text.indexOf('\n') + 1);
  } finally {
    await handle.close();
  }
}

function fileId(source: ExternalSessionSource, path: string): string | undefined {
  const name = basename(path, '.jsonl');
  if (source === 'claude-code') return ID.test(name) ? name : undefined;
  const uuid = /([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})$/iu.exec(name)?.[1];
  return uuid;
}

export interface ExternalSessionRoots {
  claudeCode?: string;
  codex?: string;
}

export function defaultExternalSessionRoots(
  env: NodeJS.ProcessEnv = process.env,
  home: string = homedir(),
): ExternalSessionRoots {
  return {
    claudeCode: join(env['CLAUDE_CONFIG_DIR'] || join(home, '.claude'), 'projects'),
    codex: join(env['CODEX_HOME'] || join(home, '.codex'), 'sessions'),
  };
}

export function createExternalSessionReader(
  roots: ExternalSessionRoots = defaultExternalSessionRoots(),
): ExternalSessionReader {
  const cache = new Map<
    string,
    { mtimeMs: number; size: number; summary?: ExternalSessionSummary }
  >();
  const located = new Map<string, SessionFile>();

  const scan = async (): Promise<SessionFile[]> => {
    const found: SessionFile[] = [];
    const add = async (source: ExternalSessionSource, paths: string[]) => {
      for (const path of paths) {
        try {
          const info = await stat(path);
          found.push({ source, path, mtimeMs: info.mtimeMs, size: info.size });
        } catch {
          continue;
        }
      }
    };
    if (roots.claudeCode)
      await add('claude-code', await files(roots.claudeCode, 1, (name) => name.endsWith('.jsonl')));
    if (roots.codex)
      await add(
        'codex',
        await files(
          roots.codex,
          3,
          (name) => name.startsWith('rollout-') && name.endsWith('.jsonl'),
        ),
      );
    return found.sort((a, b) => b.mtimeMs - a.mtimeMs).slice(0, EXTERNAL_SESSION_LIST_MAX);
  };

  const summarize = async (file: SessionFile): Promise<ExternalSessionSummary | undefined> => {
    const cached = cache.get(file.path);
    if (cached !== undefined && cached.mtimeMs === file.mtimeMs && cached.size === file.size)
      return cached.summary;
    let summary: ExternalSessionSummary | undefined;
    try {
      const text = await head(file.path, HEAD_BYTES);
      const parsed =
        file.source === 'claude-code' ? parseClaudeCodeSession(text) : parseCodexSession(text);
      const id = fileId(file.source, file.path) ?? parsed.id;
      if (
        id !== undefined &&
        ID.test(id) &&
        parsed.cwd !== '' &&
        parsed.entries.some((entry) => entry.role === 'human')
      )
        summary = {
          sessionId: `${file.source}:${id}`,
          source: file.source,
          ...(parsed.title === undefined ? {} : { title: parsed.title }),
          cwd: parsed.cwd,
          lastActivityAt: Math.round(file.mtimeMs),
        };
    } catch {
      summary = undefined;
    }
    cache.set(file.path, {
      mtimeMs: file.mtimeMs,
      size: file.size,
      ...(summary === undefined ? {} : { summary }),
    });
    if (summary !== undefined) located.set(summary.sessionId, file);
    return summary;
  };

  const list = async (): Promise<ExternalSessionSummary[]> => {
    const rows: ExternalSessionSummary[] = [];
    for (const file of await scan()) {
      const summary = await summarize(file);
      if (summary !== undefined) rows.push(summary);
    }
    return rows;
  };

  return {
    list,
    async read(sessionId) {
      const parsedId = parseExternalSessionId(sessionId);
      if (parsedId === undefined) return undefined;
      let file = located.get(sessionId);
      if (file === undefined) {
        await list();
        file = located.get(sessionId);
      }
      if (file === undefined) return undefined;
      let text: string;
      try {
        const info = await stat(file.path);
        text =
          info.size > READ_BYTES
            ? `${await head(file.path, HEAD_BYTES)}\n${await tail(file.path, Math.max(info.size - READ_BYTES, HEAD_BYTES), info.size)}`
            : await readFile(file.path, 'utf8');
      } catch {
        return undefined;
      }
      const parsed =
        file.source === 'claude-code' ? parseClaudeCodeSession(text) : parseCodexSession(text);
      if (parsed.cwd === '') return undefined;
      return {
        sessionId,
        source: file.source,
        ...(parsed.title === undefined ? {} : { title: parsed.title }),
        cwd: parsed.cwd,
        lastActivityAt: Math.round(file.mtimeMs),
        entries: parsed.entries,
      };
    },
  };
}
