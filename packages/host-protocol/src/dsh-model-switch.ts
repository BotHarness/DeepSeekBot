import { isTurnTarget, type TurnModelSwitch, type TurnTarget } from './turn-target';

interface DshSessionEvent {
  type: string;
  data: unknown;
  time: number;
}

type DshTurnTarget = Extract<TurnTarget, { kind: 'dsh' }>;

interface Notice {
  from: string;
  to: string;
  time: number;
}

interface SwitchState {
  active?: DshTurnTarget;
  selected?: DshTurnTarget;
  notice?: Notice & { emitted: boolean };
}

export interface DshModelSwitchProjection {
  state: SwitchState;
  marker?: TurnModelSwitch & { time: number };
}

const MODEL_SWITCH_NOTICE =
  /^\[model changed: assistant turns above this point were generated by ([^;\]\r\n]+); the session continues with ([^\]\r\n]+)\]$/u;

function field(value: unknown, key: string): unknown {
  return typeof value === 'object' && value !== null && Object.hasOwn(value, key)
    ? Reflect.get(value, key)
    : undefined;
}

export function isModelSelectionNotice(data: unknown): boolean {
  const source = field(data, 'source') ?? field(field(data, 'message'), 'source');
  return field(source, 'kind') === 'model-selection' && field(source, 'form') === 'notice';
}

function readNotice(event: DshSessionEvent): Notice | undefined {
  const content = field(field(event.data, 'message'), 'content') ?? field(event.data, 'content');
  if (!Array.isArray(content) || content.length !== 1 || field(content[0], 'type') !== 'text')
    return;
  const text = field(content[0], 'text');
  const match = typeof text === 'string' ? MODEL_SWITCH_NOTICE.exec(text.trim()) : null;
  const from = match?.[1];
  const to = match?.[2];
  if (from && to && from !== to) return { from, to, time: event.time };
}

function target(data: unknown): DshTurnTarget | undefined {
  const candidate: unknown = {
    kind: 'dsh',
    provider: field(data, 'provider'),
    model: field(data, 'model'),
  };
  return isTurnTarget(candidate) && candidate.kind === 'dsh' ? candidate : undefined;
}

function qualified(label: string): DshTurnTarget | undefined {
  const slash = label.indexOf('/');
  if (slash > 0 && slash < label.length - 1)
    return { kind: 'dsh', provider: label.slice(0, slash), model: label.slice(slash + 1) };
}

function resolveNotice(
  notice: Notice,
  active: DshTurnTarget | undefined,
  selected: DshTurnTarget | undefined,
): DshModelSwitchProjection['marker'] {
  if (active?.model === notice.from)
    return { from: active, to: { ...active, model: notice.to }, time: notice.time };
  if (selected?.model === notice.to)
    return { from: { ...selected, model: notice.from }, to: selected, time: notice.time };
  if (active === undefined && selected === undefined) return;
  const from = qualified(notice.from);
  const to = qualified(notice.to);
  if (from !== undefined && to !== undefined && from.provider !== to.provider)
    return { from, to, time: notice.time };
}

export function isDshModelSwitchEvent(event: DshSessionEvent): boolean {
  return (
    event.type === 'request/header' ||
    event.type === 'model/selection' ||
    event.type === 'assistant/message' ||
    (event.type === 'user/message' && isModelSelectionNotice(event.data))
  );
}

export function projectDshModelSwitch(
  previous: DshModelSwitchProjection | undefined,
  event: DshSessionEvent,
): DshModelSwitchProjection {
  const state = previous?.state ?? {};
  if (event.type === 'model/selection') {
    const selected = target(event.data);
    return selected === undefined ? { state } : { state: { ...state, selected } };
  }
  if (event.type === 'user/message') {
    if (!isModelSelectionNotice(event.data)) return { state };
    const notice = readNotice(event);
    if (
      notice === undefined ||
      (state.notice?.from === notice.from && state.notice.to === notice.to)
    )
      return { state };
    const marker = resolveNotice(notice, state.active, state.selected);
    return {
      state: { ...state, notice: { ...notice, emitted: marker !== undefined } },
      ...(marker === undefined ? {} : { marker }),
    };
  }
  const active = target(
    event.type === 'request/header'
      ? field(field(event.data, 'header'), 'config')
      : field(field(event.data, 'message'), 'source'),
  );
  if (active === undefined) return { state };
  const marker =
    state.notice === undefined || state.notice.emitted
      ? undefined
      : resolveNotice(state.notice, state.active, active);
  return {
    state: { active },
    ...(marker === undefined ? {} : { marker }),
  };
}
