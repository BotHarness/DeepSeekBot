#!/usr/bin/env node
// Generates the Web outputs of the Tobs design tokens (#4282) from design/tokens/tobs.tokens.json.
// `--check` fails when a checked-in output is stale; `pnpm lint` runs it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
export const SOURCE = fileURLToPath(new URL('design/tokens/tobs.tokens.json', root));
export const CSS_OUTPUT = fileURLToPath(
  new URL('packages/client/src/client/ds/tobs-tokens.generated.ts', root),
);
export const STYLEX_OUTPUT = fileURLToPath(
  new URL('packages/client/src/client/ds/tobs.stylex.ts', root),
);
const DARK = 'app.tobs.dark';
const HEADER =
  '// Generated by scripts/generate-tokens.mjs from design/tokens/tobs.tokens.json. Do not edit.';

export function readTokens(path = SOURCE) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

/** Every token leaf as { path, type, light, dark } with aliases resolved per scheme. */
export function flatten(tree) {
  const leaves = new Map();
  const walk = (node, path) => {
    if (node && typeof node === 'object' && '$value' in node) {
      const dark = node.$extensions?.[DARK];
      leaves.set(path.join('.'), {
        path,
        type: node.$type,
        light: node.$value,
        dark: dark ?? node.$value,
      });
      return;
    }
    for (const [key, child] of Object.entries(node)) {
      if (!key.startsWith('$')) walk(child, [...path, key]);
    }
  };
  walk(tree, []);
  const resolve = (value, scheme, seen = new Set()) => {
    if (typeof value !== 'string') return value;
    const alias = /^\{([^}]+)\}$/.exec(value);
    if (!alias) return value;
    const target = leaves.get(alias[1]);
    if (!target) throw new Error(`Unknown token alias ${value}`);
    if (seen.has(alias[1])) throw new Error(`Cyclic token alias ${value}`);
    return resolve(target[scheme], scheme, new Set([...seen, alias[1]]));
  };
  return [...leaves.values()].map((leaf) => ({
    ...leaf,
    light: resolve(leaf.light, 'light'),
    dark: resolve(leaf.dark, 'dark'),
  }));
}

const camel = (parts) =>
  parts
    .join('-')
    .replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
    .replace(/^(\d)/, 'x$1');

/** Web semantic tokens that switch with the colour scheme become custom properties. */
export function cssName(path) {
  const rest = path[0] === 'web' ? path.slice(1) : path;
  return `--tobs-${(rest[0] === 'color' ? rest.slice(1) : rest).join('-')}`;
}

const SCHEMED = new Set(['color', 'shadow']);

export function webTokens(tree = readTokens()) {
  const leaves = flatten(tree);
  const web = leaves.filter((leaf) => leaf.path[0] === 'web');
  const vars = web.filter((leaf) => SCHEMED.has(leaf.type));
  const scheme = (key) => Object.fromEntries(vars.map((leaf) => [cssName(leaf.path), leaf[key]]));
  const accents = Object.fromEntries(
    leaves
      .filter((leaf) => leaf.path.slice(0, 3).join('.') === 'core.color.accent')
      .map((leaf) => [leaf.path[3], { light: leaf.light, dark: leaf.dark }]),
  );
  const breakpoints = Object.fromEntries(
    leaves
      .filter((leaf) => leaf.path[0] === 'core' && leaf.path[1] === 'breakpoint')
      .map((leaf) => [leaf.path[2], leaf.light]),
  );
  return { leaves: web, light: scheme('light'), dark: scheme('dark'), accents, breakpoints };
}

const literal = (value) =>
  Array.isArray(value)
    ? `'cubic-bezier(${value.join(', ')})'`
    : typeof value === 'number'
      ? `'${value}'`
      : String(value).includes("'")
        ? `"${value}"`
        : `'${value}'`;

export function renderCss(tokens = webTokens()) {
  const block = (values) =>
    Object.entries(values)
      .map(([name, value]) => `    '${name}': ${literal(value)},`)
      .join('\n');
  const accents = Object.entries(tokens.accents)
    .map(
      ([name, { light, dark }]) =>
        `  '${name}': { light: ${literal(light)}, dark: ${literal(dark)} },`,
    )
    .join('\n');
  const breakpoints = Object.entries(tokens.breakpoints)
    .map(([name, value]) => `  ${camel([name])}: ${literal(value)},`)
    .join('\n');
  return `${HEADER}

export const TOBS_TOKENS = {
  light: {
${block(tokens.light)}
  },
  dark: {
${block(tokens.dark)}
  },
} as const;

export const TOBS_ACCENTS = {
${accents}
} as const;

export const TOBS_BREAKPOINTS = {
${breakpoints}
} as const;
`;
}

export function renderStylex(tokens = webTokens()) {
  const groups = new Map();
  for (const leaf of tokens.leaves) {
    const [, group, ...rest] = leaf.path;
    const key = group === 'color' ? rest[0] : group;
    const name = camel(group === 'color' ? rest.slice(1) : rest);
    const value = SCHEMED.has(leaf.type) ? `var(${cssName(leaf.path)})` : leaf.light;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(`  ${name}: ${literal(value)},`);
  }
  const blocks = [...groups]
    .map(
      ([group, lines]) => `export const ${camel([group])} = stylex.defineConsts({
${lines.join('\n')}
});`,
    )
    .join('\n\n');
  return `${HEADER}
import * as stylex from '@stylexjs/stylex';

${blocks}
`;
}

/** WCAG relative-luminance contrast of two opaque or translucent hex colours over a backdrop. */
export function contrast(foreground, background, backdrop = '#ffffff') {
  const parse = (hex) => {
    let digits = hex.slice(1);
    if (digits.length <= 4) digits = [...digits].map((d) => d + d).join('');
    const channel = (at) => Number.parseInt(digits.slice(at, at + 2), 16);
    return [channel(0), channel(2), channel(4), digits.length === 8 ? channel(6) / 255 : 1];
  };
  const over = (top, under) => {
    const [r, g, b, a] = parse(top);
    const [ur, ug, ub] = under;
    return [r * a + ur * (1 - a), g * a + ug * (1 - a), b * a + ub * (1 - a)];
  };
  const base = over(backdrop, [255, 255, 255]);
  const bg = over(background, base);
  const fg = over(foreground, bg);
  const luminance = (rgb) => {
    const [r, g, b] = rgb.map((v) => {
      const c = v / 255;
      return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
    });
    return 0.2126 * r + 0.7152 * g + 0.0722 * b;
  };
  const [hi, lo] = [luminance(fg), luminance(bg)].sort((a, b) => b - a);
  return (hi + 0.05) / (lo + 0.05);
}

const OUTPUTS = [
  [CSS_OUTPUT, renderCss],
  [STYLEX_OUTPUT, renderStylex],
];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tokens = webTokens();
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [path, render] of OUTPUTS) {
    const next = render(tokens);
    if (!check) {
      writeFileSync(path, next);
      continue;
    }
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {}
    if (current !== next) {
      stale = true;
      console.error(
        `${fileURLToPath(new URL(path, 'file://'))} is stale; run node scripts/generate-tokens.mjs`,
      );
    }
  }
  if (stale) process.exit(1);
  if (check) console.log('Tobs design token outputs are current.');
}
